import esbuild from 'esbuild';
import process from 'process';
import { copyFile, mkdir, readFile, stat } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const RELEASE_FILES = ['main.js', 'manifest.json', 'styles.css'];

/** Copies the release files into `$OBSIDIAN_VAULT/.obsidian/plugins/<id>/` after each build. */
const installToVault = {
	name: 'install-to-vault',
	async setup(build) {
		const vault = process.env.OBSIDIAN_VAULT;
		if (!vault) return;

		// Node's --env-file doesn't expand ~, so a .env path like ~/vault arrives literally.
		const root = resolve(vault.replace(/^~(?=$|[\\/])/, homedir()));
		const config = join(root, '.obsidian');
		if (!(await stat(config).catch(() => null))?.isDirectory())
			throw new Error(`OBSIDIAN_VAULT is not a vault (no .obsidian folder): ${root}`);

		const { id } = JSON.parse(await readFile('manifest.json', 'utf8'));
		const target = join(config, 'plugins', id);

		build.onEnd(async (result) => {
			if (result.errors.length) return;
			await mkdir(target, { recursive: true });
			await Promise.all(RELEASE_FILES.map((file) => copyFile(file, join(target, file))));
			console.log(`Installed to ${target}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [installToVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
